const DICTIONARIES = { en, fr, es, de, pt, it };

/** The browser's first preferred language we have, else English. */
function detectLanguage() {
  try {
    const preferred = navigator.languages?.length ? navigator.languages : [navigator.language];
    for (const tag of preferred) {
      const code = String(tag || "").toLowerCase().split("-")[0];
      if (DICTIONARIES[code]) return { code, tag };
    }
  } catch {
    /* no navigator (tests): English */
  }
  return { code: "en", tag: "en" };
}

const detected = detectLanguage();
export const LANG = detected.code;
/** For number formatting (thousands separators the local way). */
export const LOCALE = detected.tag;

export function t(key, vars) {
  let text = DICTIONARIES[LANG][key] ?? en[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  return text;
}

/** A number formatted for the player's language. */
export function formatNumber(value) {
  try {
    return Number(value).toLocaleString(LOCALE);
  } catch {
    return String(value);
  }
}
